#!/usr/bin/env python3
"""Prepare Flutter native projects in a generated application; never builds or signs."""
import argparse
import json
from pathlib import Path
import plistlib
import re
import shutil
import subprocess
import xml.etree.ElementTree as ET


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--application', type=Path, default=Path('.'))
    args = parser.parse_args()
    root = args.application.resolve()
    config = json.loads((root / 'application.json').read_text())
    if not re.fullmatch(r'[a-z][a-z0-9_]{1,49}', config['name']) or not re.fullmatch(r'[a-z][a-z0-9]*(\.[a-z][a-z0-9]*)+', config['organization']):
        parser.error('invalid application identifiers')
    flutter = shutil.which('flutter')
    if not flutter:
        parser.error('Flutter SDK is not installed; sources were not changed')
    client = root / 'client'
    # Refuse to rerun on an existing native project: this is initialization,
    # never an implicit migration or replacement of platform-specific code.
    if config.get('nativeScaffolded') or any((client / name).exists() for name in ['android', 'ios', 'windows', 'macos']):
        parser.error('native scaffolding already exists; review changes manually')
    preserved = {}
    for path in client.rglob('*'):
        if path.is_symlink():
            parser.error('client source links are not supported')
        if path.is_file() and not any(part in {'.dart_tool', 'build', '__pycache__'} for part in path.relative_to(client).parts):
            preserved[path.relative_to(client)] = path.read_bytes()
    try:
        subprocess.run([flutter, 'create', '--no-pub', '--platforms=web,ios,android,windows,macos', '--org', config['organization'], '--project-name', config['name'], str(client)], check=True)
    finally:
        # Always restore reviewed source, even if Flutter failed partway.
        for name, body in preserved.items():
            destination = client / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(body)
    # The counter-app test generated by Flutter does not describe this app.
    for path in (client / 'test').rglob('*'):
        if path.is_file() and path.relative_to(client) not in preserved:
            path.unlink()
    build = client / 'android/app/build.gradle.kts'
    original = build.read_text()
    marker = 'signingConfig = signingConfigs.getByName("debug")'
    if original.count(marker) != 1:
        parser.error('unrecognized Android release signing scaffold; review generated sources')
    build.write_text(original.replace(marker, 'signingConfig = null'))
    ns = 'http://schemas.android.com/apk/res/android'
    ET.register_namespace('android', ns)
    for variant in ['main', 'debug']:
        path = client / 'android/app/src' / variant / 'AndroidManifest.xml'
        tree = ET.parse(path)
        manifest = tree.getroot()
        if variant == 'main':
            if not any(node.get('{' + ns + '}name') == 'android.permission.INTERNET' for node in manifest.findall('uses-permission')):
                ET.SubElement(manifest, 'uses-permission', {'{' + ns + '}name': 'android.permission.INTERNET'})
        else:
            application = manifest.find('application')
            if application is None:
                application = ET.SubElement(manifest, 'application')
            application.set('{' + ns + '}usesCleartextTraffic', 'true')
        tree.write(path, encoding='utf-8', xml_declaration=True)
    for name in ['DebugProfile.entitlements', 'Release.entitlements']:
        path = client / 'macos/Runner' / name
        with path.open('rb') as stream:
            entitlements = plistlib.load(stream)
        entitlements['com.apple.security.network.client'] = True
        with path.open('wb') as stream:
            plistlib.dump(entitlements, stream, sort_keys=False)
    config['nativeScaffolded'] = True
    config['androidUnsignedRelease'] = True
    (root / 'application.json').write_text(json.dumps(config, indent=2) + '\n')
    print('Native projects prepared. No build, signature, installation or publication was performed.')


if __name__ == '__main__':
    main()
